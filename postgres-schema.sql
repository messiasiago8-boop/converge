CREATE TABLE IF NOT EXISTS usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL, email text UNIQUE NOT NULL, senha text NOT NULL,
  data_criacao text DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS entradas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer REFERENCES usuarios(id) ON DELETE CASCADE,
  descricao text NOT NULL, valor double precision NOT NULL,
  data text DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS despesas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer REFERENCES usuarios(id) ON DELETE CASCADE,
  descricao text NOT NULL, valor double precision NOT NULL, categoria text NOT NULL,
  data text DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS limites (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  categoria text NOT NULL, valor_maximo double precision NOT NULL DEFAULT 0,
  UNIQUE (usuario_id, categoria)
);
CREATE TABLE IF NOT EXISTS potes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer REFERENCES usuarios(id) ON DELETE CASCADE,
  nome text NOT NULL, tipo text NOT NULL, categoria_ativo text DEFAULT 'CDB',
  taxa_anual_pct double precision DEFAULT 10.75, rendimento_mensal_pct double precision DEFAULT 0.85,
  instituicao text, vencimento text, valor double precision NOT NULL,
  data text DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS projetos_compras (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer REFERENCES usuarios(id) ON DELETE CASCADE,
  nome text NOT NULL, tipo text NOT NULL, valor_objetivo double precision NOT NULL,
  valor_acumulado double precision NOT NULL DEFAULT 0,
  data_criacao text DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS aportes_projetos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer REFERENCES usuarios(id) ON DELETE CASCADE,
  projeto_id integer NOT NULL REFERENCES projetos_compras(id) ON DELETE CASCADE,
  valor double precision NOT NULL,
  data text DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS investimentos_mensais (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  mes text NOT NULL, tipo_ativo text NOT NULL, valor_aplicado double precision NOT NULL,
  rendimento_atual double precision NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS portal_dados (
  usuario_id integer PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
  dados jsonb NOT NULL,
  versao integer NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS portal_config (
  chave text PRIMARY KEY,
  dados jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pg_entradas_usuario ON entradas (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pg_despesas_usuario ON despesas (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pg_potes_usuario ON potes (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pg_projetos_usuario ON projetos_compras (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pg_aportes_projeto ON aportes_projetos (projeto_id, usuario_id);
CREATE INDEX IF NOT EXISTS idx_pg_investimentos_usuario_mes ON investimentos_mensais (usuario_id, mes);

CREATE OR REPLACE FUNCTION atualizar_saldo_apos_aporte_pg() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE projetos_compras SET valor_acumulado = valor_acumulado + NEW.valor
    WHERE id = NEW.projeto_id AND usuario_id = NEW.usuario_id;
  RETURN NEW;
END;
$$;
CREATE OR REPLACE TRIGGER atualizar_saldo_apos_aporte
  AFTER INSERT ON aportes_projetos FOR EACH ROW EXECUTE FUNCTION atualizar_saldo_apos_aporte_pg();
